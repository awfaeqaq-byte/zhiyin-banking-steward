import {readFileSync,writeFileSync,existsSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
const directory=new URL('../src/prompts/',import.meta.url);
const content='// Generated by scripts/sync-steward-prompts.mjs; edit the .md sources.\n'+
 ['financial-coach','wealth-advisor'].map(name=>`export const ${name==='financial-coach'?'financialCoachPrompt':'wealthAdvisorPrompt'} = ${JSON.stringify(readFileSync(new URL(`${name}.v1.md`,directory),'utf8'))};\n`).join('');
const output=fileURLToPath(new URL('runtime.generated.ts',directory));
if(!existsSync(output)||readFileSync(output,'utf8')!==content)writeFileSync(output,content);
