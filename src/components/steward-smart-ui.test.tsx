import {act,render,screen,waitFor,within} from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import {expect,it,vi} from 'vitest';
import {StewardChatHome} from './steward-chat-home';
import type {ConnectedFinancialSource} from '../lib/financial-connections';
import type {StewardReplyFn} from '../lib/steward-chat';
import type {SubscriptionSyncResult} from '../lib/use-subscription-sync';

const source:ConnectedFinancialSource={provider:'wechat_pay',displayName:'微信支付',accountMasked:'测试',scopes:['transactions'],syncedAt:'2026-09-24',autopays:[],transactions:[{id:'lunch',title:'午餐',amount:-2500,category:'餐饮',occurredAt:'2026-09-20'}]};
const base={seamless:true,stewardName:'宁宁',stewardImage:'/n.png',disabledReminders:[],onToggleReminder:vi.fn(),onOpenSubscriptions:vi.fn(),onPrepareCancel:vi.fn(),now:Date.parse('2026-09-24')};
it('切换账单平台不发消息或重算解读，刷新保留范围，下一句沿用当前展示',async()=>{
 const user=userEvent.setup(),reply=vi.fn<StewardReplyFn>(async()=>({text:'原范围的解读。'}));
 const alipay={...source,provider:'alipay' as const,displayName:'支付宝',transactions:[{id:'metro',title:'地铁',amount:-500,category:'出行',occurredAt:'2026-09-20'}]};
 const props={...base,connections:{wechat_pay:source,alipay},reply};
 const view=render(<StewardChatHome {...props}/>);
 await user.type(screen.getByRole('textbox'),'本月支出');await user.click(screen.getByRole('button',{name:'发送给宁宁'}));
 const scene=await screen.findByRole('region',{name:'账单工作区'});
 const before=JSON.parse(localStorage.getItem('zhiyin-steward-conversation-v1')!);
 await user.click(within(scene).getByRole('button',{name:'只看支付宝'}));
 expect(within(scene).getAllByText('¥5')[0]).toBeVisible();
 expect(reply).toHaveBeenCalledTimes(1);
 expect(JSON.parse(localStorage.getItem('zhiyin-steward-conversation-v1')!)).toEqual(before);
 await user.click(within(scene).getByRole('button',{name:/查看出行交易/}));
 expect(reply).toHaveBeenCalledTimes(1);
 view.unmount();render(<StewardChatHome {...props}/>);
 expect(screen.getByRole('button',{name:'只看支付宝'})).toHaveAttribute('aria-pressed','true');
 expect(screen.getByRole('heading',{name:'出行交易'})).toBeVisible();
 await user.type(screen.getByRole('textbox'),'有没有问题');await user.click(screen.getByRole('button',{name:'发送给宁宁'}));
 await waitFor(()=>expect(reply).toHaveBeenCalledTimes(2));
 expect(reply.mock.calls[1][0].billAnalysis?.sources).toEqual(['支付宝']);
 expect(reply.mock.calls[1][0].billCategory).toBe('出行');
});
it('模型遗漏入口仍展示账单读取现场，完成双边授权后自动继续原问题',async()=>{
 const user=userEvent.setup(),connect=vi.fn(async()=>source),open=vi.fn();
 const reply=vi.fn<StewardReplyFn>(async request=>({text:request.billAnalysis?.count?'餐饮是这段支出的主要部分。':'需要你确认账单读取范围。'}));
 render(<StewardChatHome {...base} connections={{}} reply={reply} onConnectSource={connect} onOpenConnections={open}/>);
 await user.type(screen.getByRole('textbox'),'看看8月支出');await user.click(screen.getByRole('button',{name:'发送给宁宁'}));
 const consent=await screen.findByRole('region',{name:'账单读取范围'});
 expect(connect).not.toHaveBeenCalled();expect(open).not.toHaveBeenCalled();
 await user.click(within(consent).getByRole('checkbox',{name:'支付宝'}));
 await user.click(within(consent).getByRole('button',{name:'继续到平台确认'}));
 await waitFor(()=>expect(reply).toHaveBeenCalledTimes(2));
 expect(reply.mock.calls[1][0].billAnalysis).toMatchObject({from:'2026-08-01',to:'2026-08-31',sources:['微信支付']});
 expect(screen.getAllByText('看看8月支出',{selector:'.steward-message.user p'})).toHaveLength(1);
 expect(screen.queryByRole('region',{name:'账单读取范围'})).not.toBeInTheDocument();
 expect(await screen.findByRole('region',{name:'账单工作区'})).toHaveTextContent('2026-08-01');
});
it('刷新恢复的账单先重新核对平台，不把缓存金额当成最新结果',async()=>{
 localStorage.setItem('zhiyin-steward-conversation-v1',JSON.stringify([{id:'bill-answer',role:'assistant',content:'上次的分析。'}]));
 localStorage.setItem('zhiyin-bill-scenes-v1',JSON.stringify([{key:'bill',anchorId:'bill-answer',question:'本月支出'}]));
 let resolve!:(value:SubscriptionSyncResult)=>void;
 const refresh=vi.fn(()=>new Promise<SubscriptionSyncResult>(done=>{resolve=done;}));
 render(<StewardChatHome {...base} connections={{wechat_pay:source}} refreshSubscriptions={refresh} onConnectSource={vi.fn()}/>);
 expect(screen.queryAllByText('¥25')).toHaveLength(0);
 await act(async()=>{resolve({connections:{},error:'微信授权已失效'});});
 expect(await screen.findByRole('alert')).toHaveTextContent('授权已失效');
 expect(screen.queryAllByText('¥25')).toHaveLength(0);
});
it('恢复授权界面期间先核对权限，不能用缓存的授权范围提前继续',async()=>{
 localStorage.setItem('zhiyin-steward-conversation-v1',JSON.stringify([{id:'bill-answer',role:'assistant',content:'请确认读取范围。'}]));
 localStorage.setItem('zhiyin-bill-scenes-v1',JSON.stringify([{key:'bill',anchorId:'bill-answer',question:'本月支出',needsConsent:true,provider:'wechat_pay'}]));
 let resolve!:(value:SubscriptionSyncResult)=>void;
 render(<StewardChatHome {...base} connections={{wechat_pay:source}} refreshSubscriptions={()=>new Promise(done=>{resolve=done;})} onConnectSource={vi.fn()}/>);
 expect(screen.getByRole('button',{name:'继续分析账单'})).toBeDisabled();
 await act(async()=>resolve({connections:{},error:''}));
 expect(screen.getByRole('button',{name:'继续到平台确认'})).toBeEnabled();
});
it('点选交易后说这笔时沿用同一交易，而不是只记得一句无对象的提问',async()=>{
 const user=userEvent.setup(),reply=vi.fn<StewardReplyFn>(async()=>({text:'这笔可以核对。'}));
 render(<StewardChatHome {...base} connections={{wechat_pay:source}} reply={reply} onConnectSource={vi.fn()}/>);
 await user.type(screen.getByRole('textbox'),'本月支出');await user.click(screen.getByRole('button',{name:'发送给宁宁'}));
 await user.click(within(await screen.findByRole('region',{name:'账单工作区'})).getByRole('button',{name:/查看餐饮交易/}));
 await user.click(screen.getByRole('button',{name:/请宁宁解释午餐/}));
 await waitFor(()=>expect(reply).toHaveBeenCalledTimes(2));
 await user.type(screen.getByRole('textbox'),'这笔什么时候付的');await user.click(screen.getByRole('button',{name:'发送给宁宁'}));
 await waitFor(()=>expect(reply).toHaveBeenCalledTimes(3));
 expect(reply.mock.calls[2][0].billFocus).toEqual({provider:'wechat_pay',id:'lunch'});
});
