import {cleanup,render,screen,waitFor} from '@testing-library/react';
import {afterEach,expect,it,vi} from 'vitest';
import {StewardChatHome} from './steward-chat-home';
import type {ConversationEntry} from '../lib/message-flow';
afterEach(()=>{cleanup();localStorage.clear();vi.restoreAllMocks();});
const props={seamless:true,homePreview:true,stewardName:'宁宁',stewardImage:'/n.png',connections:{},disabledReminders:[],onToggleReminder:vi.fn(),onOpenSubscriptions:vi.fn(),onPrepareCancel:vi.fn()};
const entry=(id:string,content=id):ConversationEntry=>({id,role:'user',content});
it('服务器已有100条时，不把本地旧缓存重新追加到尾部',async()=>{
 localStorage.setItem('zhiyin-steward-conversation-v1',JSON.stringify([entry('old-cache','旧生日对话')]));
 const sync=vi.fn<(entries:ConversationEntry[])=>Promise<void>>(async()=>{}),messages=Array.from({length:100},(_,i)=>entry(`server-${i}`));
 const view=render(<StewardChatHome {...props} onConversationEntries={sync}/>);
 view.rerender(<StewardChatHome {...props} conversationMessages={messages} onConversationEntries={sync}/>);
 await screen.findByText('server-99');
 expect(screen.queryByText('旧生日对话')).not.toBeInTheDocument();
 expect(sync.mock.calls.flatMap(call=>call[0] as ConversationEntry[]).some(m=>m.id==='old-cache')).toBe(false);
});
it('服务端窗口向前滚动后，已淘汰消息不复活；晚到回复按消息ID紧跟自己的提问',async()=>{
 const sync=vi.fn<(entries:ConversationEntry[])=>Promise<void>>(async()=>{}),first:ConversationEntry[]=[entry('user-one','现在转账'),entry('user-two','你好')];
 first[0].messageId='one';first[1].messageId='two';
 const view=render(<StewardChatHome {...props} conversationMessages={first} onConversationEntries={sync}/>);
 await screen.findByText('现在转账');
 const reply:ConversationEntry={id:'answer-one',role:'assistant',content:'先核对转账方案',messageId:'one'};
 view.rerender(<StewardChatHome {...props} conversationMessages={[...first,reply]} onConversationEntries={sync}/>);
 const answer=await screen.findByText('先核对转账方案');
 expect(answer.compareDocumentPosition(screen.getByText('你好'))&Node.DOCUMENT_POSITION_FOLLOWING).toBeTruthy();
 sync.mockClear();
 view.rerender(<StewardChatHome {...props} conversationMessages={[first[1]]} onConversationEntries={sync}/>);
 await waitFor(()=>expect(screen.queryByText('现在转账')).not.toBeInTheDocument());
 expect(screen.queryByText('先核对转账方案')).not.toBeInTheDocument();
 expect(sync.mock.calls.flatMap(call=>call[0]).some(m=>m.id==='user-one'||m.id==='answer-one')).toBe(false);
});
